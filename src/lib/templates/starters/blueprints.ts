// The six starter blueprints, transcribed from Appendix A of the seeding
// spec. Geometry, copy, ramps, and slots come from the appendix verbatim —
// nothing here is invented, and nothing here is a literal color or font: the
// materializer resolves every slot per tenant.
//
// Field order is BOTH paint order and member form order. Frame and backer
// shapes (a logo's border, an image slot's surfaceAlt wash) sit immediately
// before the field they decorate so the renderer's DOM-order tiebreak paints
// them underneath; being static, they never reach the member form.
//
// Wrapping: headline-class fields (Display ramps, and the plated CTAs) are
// authored per the appendix with textSizing "shrink" and a minFontSizePx of
// 60% of the ramp size. Note the render pipeline ignores textSizing on
// PLATED fields — a plate hugs its text at the authored size (layout.ts), so
// the CTAs' shrink is stored but inert; long CTA copy grows the pill.

import type { StarterBlueprint, StarterField } from "./types";

type Ramp = Pick<
  StarterField,
  "font" | "fontWeight" | "fontSizePx" | "lineHeight" | "letterSpacingPx" | "uppercase"
>;

