/** Shrink floor: 60% of the ramp size, rounded. */
const floor = (ramp: Ramp): number => Math.round(ramp.fontSizePx! * 0.6);

/** The tenant logo slot plus its 1px border frame. Strokes are shape-only
 * on this model (types.ts: "Shape fields only"; ImageFieldBox renders none),
 * so the border is a static transparent rect drawn at the same geometry —
 * omitted together with the logo via omitWith. */
const logoSlot = (x: number, y: number, w: number, h: number): StarterField[] => [
  {
    fieldKey: "logo_frame",
    label: "Logo frame",
    type: "shape",
    shape: "rect",
    static: true,
    omitWith: "logo",
    x,
    y,
    width: w,
    height: h,
    strokeColor: "border",
    strokeWidthPx: 1,
  },
  {
    fieldKey: "logo",
    label: "Logo",
    type: "image",
    role: "logo",
    x,
    y,
    width: w,
    height: h,
    objectFit: "contain",
  },
];

/** An editable photo slot over a surfaceAlt wash. The wash is what the
 * appendix's "fill surfaceAlt" means: the slot reads as part of the design
 * before a photo lands, and the Dark variant recolors it. */
const imageSlot = (
  fieldKey: string,
  label: string,
  placeholder: string,
  x: number,
  y: number,
  w: number,
  h: number,
): StarterField[] => [
  {
    fieldKey: `${fieldKey}_bg`,
    label: `${label} backdrop`,
    type: "shape",
    shape: "rect",
    static: true,
    x,
    y,
    width: w,
    height: h,
    colorHex: "surfaceAlt",
  },
  {
    fieldKey,
    label,
    type: "image",
    placeholder,
    x,
    y,
    width: w,
    height: h,
    objectFit: "cover",
  },
];

